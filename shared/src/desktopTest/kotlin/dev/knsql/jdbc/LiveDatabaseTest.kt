package dev.knsql.jdbc

import dev.knsql.model.ColumnSpec
import dev.knsql.model.ConnectionDraft
import dev.knsql.model.Engine
import dev.knsql.model.MetaNode
import dev.knsql.model.NodeKind
import dev.knsql.model.TableRef
import dev.knsql.sql.PendingChanges
import dev.knsql.sql.addColumnDdl
import dev.knsql.sql.alterColumnDdl
import dev.knsql.sql.buildDataChanges
import kotlinx.coroutines.runBlocking
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

/**
 * End-to-end runs through [JdbcDatabaseClient]: browse, preview, edit rows, alter a column, export DDL.
 * SQLite always runs on a temp file. PostgreSQL and MariaDB run when their servers are given:
 * KNSQL_IT_POSTGRES / KNSQL_IT_MARIADB = host:port:database:user:password.
 */
class LiveDatabaseTest {
    private fun server(name: String, engine: Engine): ConnectionDraft? {
        val spec = System.getenv(name)?.takeIf { it.isNotBlank() } ?: return null
        val (host, port, database, user, password) = spec.split(":", limit = 5)
        return ConnectionDraft(
            name = engine.label, engine = engine, host = host, port = port, database = database,
            username = user, password = password,
        )
    }

    @Test
    fun sqlite() = runBlocking {
        val file = java.io.File.createTempFile("knsql-it", ".db").apply { delete(); deleteOnExit() }
        val draft = ConnectionDraft(name = "it", engine = Engine.Sqlite, database = file.absolutePath)
        scenario(draft, container = null, table = TableRef(null, null, "items"))
        // A table without a primary key is edited through its rowid.
        val client = JdbcDatabaseClient
        val session = client.open(draft)
        try {
            client.execute(session.handle, "CREATE TABLE notes (body TEXT)", 0, 30)
            client.execute(session.handle, "INSERT INTO notes VALUES ('a'), ('b')", 0, 30)
            val structure = client.tableStructure(session.handle, TableRef(null, null, "notes"))
            val data = client.loadEditable(session.handle, structure, 100)
            assertEquals(listOf("rowid"), data.keyNames)
            client.applyChanges(session.handle, buildDataChanges(data, PendingChanges(edits = mapOf(1 to mapOf(0 to "c")))))
            val rows = client.execute(session.handle, "SELECT body FROM notes ORDER BY rowid", 0, 30).single().rows
            assertEquals(listOf("a", "c"), rows.map { it[0] })
        } finally {
            client.close(session.handle)
        }
        // Read-only sessions open the file read-only.
        val readOnly = client.open(draft.copy(readOnly = true))
        try {
            assertTrue(runCatching { client.execute(readOnly.handle, "INSERT INTO notes VALUES ('x')", 0, 30) }.isFailure)
        } finally {
            client.close(readOnly.handle)
        }
    }

    @Test
    fun postgres() = runBlocking {
        val draft = server("KNSQL_IT_POSTGRES", Engine.PostgreSql) ?: return@runBlocking
        val setup = JdbcDatabaseClient.open(draft)
        JdbcDatabaseClient.execute(setup.handle, "DROP SCHEMA IF EXISTS knsql_it CASCADE; CREATE SCHEMA knsql_it", 0, 30)
        JdbcDatabaseClient.close(setup.handle)
        scenario(draft, container = "knsql_it", table = TableRef(null, "knsql_it", "items"))
    }

    @Test
    fun mariaDb() = runBlocking {
        val draft = server("KNSQL_IT_MARIADB", Engine.MariaDb) ?: return@runBlocking
        val setup = JdbcDatabaseClient.open(draft)
        JdbcDatabaseClient.execute(setup.handle, "DROP DATABASE IF EXISTS knsql_it", 0, 30)
        JdbcDatabaseClient.execute(setup.handle, "CREATE DATABASE knsql_it", 0, 30)
        JdbcDatabaseClient.close(setup.handle)
        scenario(draft, container = "knsql_it", table = TableRef("knsql_it", null, "items"))
    }

    private suspend fun scenario(draft: ConnectionDraft, container: String?, table: TableRef) {
        val client = JdbcDatabaseClient
        val engine = draft.engine
        println("[${engine.label}] " + client.test(draft).replace('\n', ' '))
        val session = client.open(draft)
        val h = session.handle
        try {
            val name = dev.knsql.model.qualifiedName(engine, table.catalog, table.schema, table.name)
            val (idType, extra) = when (engine) {
                Engine.PostgreSql -> "integer GENERATED BY DEFAULT AS IDENTITY" to ", flag boolean DEFAULT false, born date, seen timestamp"
                Engine.Sqlite -> "INTEGER" to ", flag BOOLEAN DEFAULT 0, born DATE, seen DATETIME"
                else -> "int AUTO_INCREMENT" to ", flag tinyint(1) DEFAULT 0, born date, seen datetime"
            }
            client.execute(h, "CREATE TABLE $name (id $idType PRIMARY KEY, title varchar(40) NOT NULL$extra)", 0, 30)
            client.execute(h, "INSERT INTO $name (title, born, seen) VALUES ('one', '2024-01-31', '2024-01-31 08:30:00')", 0, 30)
            client.execute(h, "CREATE VIEW ${dev.knsql.model.qualifiedName(engine, table.catalog, table.schema, "items_v")} AS SELECT id FROM $name", 0, 30)
            if (engine == Engine.PostgreSql) {
                client.execute(h, "COMMENT ON TABLE $name IS 'things'", 0, 30)
                client.execute(h, "CREATE INDEX items_title ON $name (title)", 0, 30)
            }

            // Object tree
            val roots = client.children(h, MetaNode("s", NodeKind.Session))
            val relations = if (container == null) {
                roots
            } else {
                val root = roots.firstOrNull { it.label == container } ?: error("no $container in ${roots.map { it.label }}")
                client.children(h, root)
            }
            val tableNode = relations.firstOrNull { it.relation == "items" && it.kind == NodeKind.Table }
                ?: error("items not listed: ${relations.map { it.label }}")
            assertTrue(relations.any { it.relation == "items_v" && it.kind == NodeKind.View }, "view not listed")
            val columns = client.children(h, tableNode)
            assertTrue(columns.size >= 3, "columns: $columns")

            // Preview
            val preview = dev.knsql.model.previewSql(engine, tableNode.catalog, tableNode.schema, "items")
            val result = client.execute(h, preview, 200, 30).single()
            assertEquals(1, result.rows.size, preview)

            // Edit rows by primary key
            val structure = client.tableStructure(h, TableRef(tableNode.catalog ?: table.catalog, tableNode.schema, "items"))
            assertEquals(listOf("id"), structure.keyColumns)
            assertTrue(structure.columns.first { it.name == "id" }.autoIncrement, "id should be auto increment")
            val data = client.loadEditable(h, structure, 100)
            assertEquals(1, data.rows.size)
            val title = structure.columns.indexOfFirst { it.name == "title" }
            val flag = structure.columns.indexOfFirst { it.name == "flag" }
            val born = structure.columns.indexOfFirst { it.name == "born" }
            val seen = structure.columns.indexOfFirst { it.name == "seen" }
            val changes = PendingChanges(
                edits = mapOf(0 to mapOf(title to "uno", flag to "1", seen to "2024-02-01 09:00:00")),
                inserts = listOf(mapOf(title to "two", born to "2024-03-01")),
            )
            val affected = client.applyChanges(h, buildDataChanges(data, changes))
            assertEquals(2, affected)
            val after = client.loadEditable(h, structure, 100)
            assertEquals(listOf("uno", "two"), after.rows.map { it.values[title] })
            println("[${engine.label}] rows " + after.rows.map { it.values })

            // Structure change
            val titleColumn = structure.columns[title]
            if (engine == Engine.Sqlite) {
                client.alterTable(h, structure, alterColumnDdl(structure, titleColumn, ColumnSpec("name", titleColumn.type, false, null, null)))
                client.alterTable(h, structure, addColumnDdl(structure, ColumnSpec("note", "TEXT", true, "'n'", null)))
            } else {
                client.alterTable(
                    h, structure,
                    alterColumnDdl(structure, titleColumn, ColumnSpec("name", "varchar(60)", true, "'x'", "the name")),
                )
                client.alterTable(h, structure, addColumnDdl(structure, ColumnSpec("note", "varchar(10)", true, null, "a note")))
            }
            val altered = client.tableStructure(h, structure.table)
            val renamed = altered.columns.first { it.name == "name" }
            assertTrue(altered.columns.any { it.name == "note" })
            if (engine != Engine.Sqlite) {
                assertEquals("the name", renamed.comment)
                assertTrue(renamed.nullable)
                assertTrue(renamed.type.contains("60"), renamed.type)
                val comments = client.columnComments(h, structure.table)
                assertEquals("the name", comments["NAME"])
            }

            // DDL
            val tableDdl = client.ddl(h, tableNode) {}
            println("[${engine.label}] table DDL:\n$tableDdl")
            assertTrue(tableDdl.contains("CREATE TABLE", ignoreCase = true))
            val viewNode = relations.first { it.relation == "items_v" }
            assertTrue(client.ddl(h, viewNode) {}.contains("VIEW", ignoreCase = true))
            val whole = client.ddl(h, roots.firstOrNull { it.label == container } ?: MetaNode("s", NodeKind.Session)) {}
            assertTrue(whole.contains("items_v"), whole)
            if (engine == Engine.PostgreSql) {
                assertTrue(tableDdl.contains("items_title"), "index missing")
                assertTrue(tableDdl.contains("COMMENT ON TABLE"), "comment missing")
                // The exported DDL replays on an empty schema.
                client.execute(h, "DROP SCHEMA IF EXISTS knsql_replay CASCADE; CREATE SCHEMA knsql_replay", 0, 30)
                client.execute(h, "SET search_path TO knsql_replay", 0, 30)
                val replay = tableDdl.replace("\"knsql_it\".", "\"knsql_replay\".").replace(" knsql_it.", " knsql_replay.")
                client.execute(h, replay.lines().filterNot { it.startsWith("--") }.joinToString("\n"), 0, 30)
                println("[${engine.label}] table DDL replayed")
            }
            assertNotNull(client.execute(h, "SELECT 1", 1, 10).single())
        } finally {
            client.close(h)
        }
    }
}
